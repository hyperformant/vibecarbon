/**
 * The Compose command on a deployed server.
 *
 * A server's stack is a file set, not a file: docker-compose.yml, the prod
 * override, each enabled add-on's overlays, the DNS-01 override, and on a
 * compose-ha node the replication overlay. A bare `docker compose` reads
 * docker-compose.yml alone. There app-migrate is a build with no image, so a
 * bare `run app-migrate` tried to build on the server, where there is no build
 * context, and every compose and compose-ha restore died at its migrate step
 * (DO compose-ha scale, 2026-11-04). Hand-rolled `-f` lists drifted the same
 * way before it (scale's redis set, compose-ha's 3-file db recreate).
 *
 * So the bundle renders ONE script, `vc-compose`, next to reconcile.sh, with
 * the deploy's own set (composeFileFlags in bundle.js, the only list). Every
 * server-side Compose call runs it: reconcile.sh, the systemd unit, the add-on
 * job, the backup and TLS scripts, and every command the CLI sends over ssh,
 * as `cd /opt/<project> && ${VC_COMPOSE} <args>`.
 * tests/unit/deploy/server-compose-command-census.test.ts refuses anything
 * else.
 *
 * Nothing here imports: bundle.js, the add-on job renderer and the remote
 * callers all read it without an import cycle.
 */

/** The script's file name, in the project dir next to reconcile.sh. */
export const VC_COMPOSE_SCRIPT = 'vc-compose';

/**
 * How a server-side command spells Compose, from the project dir. Through
 * `sh`, so the file's mode never matters (the same rule as
 * `bash backup/compose-backup.sh` and `sh standby-scale.sh`).
 */
export const VC_COMPOSE = `sh ${VC_COMPOSE_SCRIPT}`;

/**
 * The replication overlay. Written only onto compose-ha nodes, after the
 * bundle lands (compose-ha's write-replication-overlay, scale's cutover), so
 * vc-compose adds it when it runs rather than when it is rendered. A single
 * compose server never has one.
 */
export const COMPOSE_REPLICATION_OVERLAY = 'docker-compose.replication.yml';

/**
 * Render vc-compose. It runs in its own directory (the project dir, where
 * compose finds the files, `.env` and the project name), appends the
 * replication overlay when the node carries it, then the caller's arguments,
 * and becomes `docker compose` (exec), so stdin and the exit status are
 * compose's own.
 *
 * @param {string} composeFlags the deploy's `-f` set (composeFileFlags)
 * @returns {string}
 */
export function renderComposeCommand(composeFlags) {
  return `#!/bin/sh
# Generated by Vibecarbon. The Compose command on this server: reconcile.sh,
# the systemd unit, the backup and TLS scripts and every command vibecarbon
# runs here call it, so each one renders the stack from the same files.
# ${COMPOSE_REPLICATION_OVERLAY} is added when this node has it (compose-ha).
cd "$(dirname "$0")" || exit 1
if [ -f ${COMPOSE_REPLICATION_OVERLAY} ]; then
  set -- -f ${COMPOSE_REPLICATION_OVERLAY} "$@"
fi
exec docker compose ${composeFlags} "$@"
`;
}
