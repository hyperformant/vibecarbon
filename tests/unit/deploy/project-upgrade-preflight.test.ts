/**
 * Deploy refuses a project an older CLI generated until `vibecarbon upgrade`
 * runs (final review I3, local half). Deployed as-is, the server restarted
 * the retired stack and the deploy waited on a migration status the old app
 * never reports, failing on a server that was actually serving.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { projectUpgradeProblem } from '../../../src/lib/deploy/preflight.js';

const TEMPLATE_COMPOSE = readFileSync(join(process.cwd(), 'carbon', 'docker-compose.yml'), 'utf8');
// The db service an older CLI generated: built on the server, no DB_IMAGE.
const RETIRED_COMPOSE = `services:
  db:
    build:
      context: ./db
    image: \${PROJECT_NAME}-db:latest
    pull_policy: build
`;
const readerFor = (files: Record<string, string>) => (path: string) =>
  files[path.split('/').pop() as string] ?? null;

describe('projectUpgradeProblem', () => {
  it('passes the shipped template (its db pulls DB_IMAGE)', () => {
    expect(TEMPLATE_COMPOSE).toContain('${DB_IMAGE');
    expect(
      projectUpgradeProblem('/p', { read: readerFor({ 'docker-compose.yml': TEMPLATE_COMPOSE }) }),
    ).toBeNull();
  });

  it('refuses the retired stack and names `vibecarbon upgrade`', () => {
    const msg = projectUpgradeProblem('/p', {
      read: readerFor({ 'docker-compose.yml': RETIRED_COMPOSE }),
    });
    expect(msg).toContain('generated by an older vibecarbon');
    expect(msg).toContain('Run `vibecarbon upgrade` first');
    expect(msg).toContain('Nothing was provisioned');
    expect(msg).not.toMatch(/—/);
  });

  it('passes a compose file with no db service at all (only positive evidence refuses)', () => {
    expect(
      projectUpgradeProblem('/p', { read: readerFor({ 'docker-compose.yml': 'services: {}\n' }) }),
    ).toBeNull();
  });

  it('refuses on either retired marker alone', () => {
    for (const compose of [
      'services:\n  db:\n    build:\n      context: ./db\n',
      `services:\n  db:\n    image: \${PROJECT_NAME}-db:latest\n`,
    ]) {
      expect(
        projectUpgradeProblem('/p', { read: readerFor({ 'docker-compose.yml': compose }) }),
      ).toContain('Run `vibecarbon upgrade` first');
    }
  });

  it('refuses a project with no docker-compose.yml, with the same next step', () => {
    expect(projectUpgradeProblem('/p', { read: () => null })).toContain(
      'Run `vibecarbon upgrade` first',
    );
  });

  it('reads <cwd>/docker-compose.yml', () => {
    const seen: string[] = [];
    projectUpgradeProblem('/proj', {
      read: (p) => {
        seen.push(p);
        return TEMPLATE_COMPOSE;
      },
    });
    expect(seen).toEqual([join('/proj', 'docker-compose.yml')]);
  });
});
