/** The perf-tracked CLI commands; two tabs show timing pairs. */
type StepKey = 'deploy' | 'backup-restore' | 'scale' | 'failover' | 'destroy';
const STEP_TABS: Array<{ key: StepKey; label: string }> = [
  { key: 'deploy', label: 'deploy' },
  { key: 'backup-restore', label: 'backup / restore' },
  { key: 'scale', label: 'scale' },
  { key: 'failover', label: 'failover' },
  { key: 'destroy', label: 'destroy' },
];

/** Pair tabs: [top, bottom] timing keys, plus the row-key labels for each. */
const PAIRS: Partial<Record<StepKey, [keyof PerfScenario, keyof PerfScenario]>> = {
  deploy: ['deploy', 'warm-deploy'],
  'backup-restore': ['backup', 'restore'],
};
const PAIR_LABELS: Partial<Record<StepKey, [string, string]>> = {
  deploy: ['New Deploy', 'Redeploy'],
  'backup-restore': ['Backup', 'Restore'],
};

/** Failover is an HA capability; it never applies to the single-* tiers. */
const HA_TIERS: ReadonlySet<TierKey> = new Set(['compose-ha', 'k8s-ha']);

function ComingSoon() {
  return (
    <span className="flex h-[44px] items-center justify-center">
      <span className="text-muted-foreground rounded-full border border-border px-2.5 py-1 text-[10.5px] font-semibold tracking-wide uppercase">
        Coming soon
      </span>
    </span>
  );
}

function Cell({
  support,
  timings,
  step,
  tier,
}: {
  support: Support;
  timings?: PerfScenario;
  step: StepKey;
  tier: TierKey;
}) {
  // A command that can never apply to this tier is a dash whatever the
  // support state — "coming soon" is reserved for cells that will one day
  // hold a number.
  if (support === 'no' || (step === 'failover' && !HA_TIERS.has(tier)))
    return (
      <span className="text-muted-foreground/50 flex h-[44px] items-center justify-center text-lg">
        —
      </span>
    );
  if (support === 'beta') {
    return (
      <span className="flex h-[44px] items-center justify-center">
        <span className="border-primary text-primary rounded-full border px-2.5 py-1 text-[10.5px] font-semibold tracking-wide uppercase">
          Beta
        </span>
      </span>
    );
  }
  if (support === 'soon') return <ComingSoon />;

  // Supported: lead with the measured timing(s) when this scenario has a
  // green CI baseline; "coming soon" otherwise — the applicable-but-unmeasured
  // cell (e.g. failover, which CI does not emit timings for yet) makes the
  // same promise as an unbuilt scenario: a number is on its way. Pair tabs
  // (deploy, backup/restore) stack two times, labeled once per table by the
  // row key; the rest are a single time.
  const pair = PAIRS[step];
  if (!pair) {
    const value = timings?.[step as keyof PerfScenario];
    if (value == null) return <ComingSoon />;
    return (
      <span className="flex h-[44px] items-center justify-center text-[17px] leading-none font-semibold tabular-nums">
        {formatDuration(value)}
      </span>
    );
  }

  const top = timings?.[pair[0]];
  const bottom = timings?.[pair[1]];
  if (top == null && bottom == null) return <ComingSoon />;
  return (
    <span className="flex h-[44px] flex-col items-center justify-center gap-2.5">
      <span className="flex h-[17px] items-center text-[17px] leading-none font-semibold tabular-nums">
        {top != null ? formatDuration(top) : '—'}
      </span>
      <span className="flex h-[17px] items-center text-[17px] leading-none font-semibold tabular-nums">
        {bottom != null ? formatDuration(bottom) : '—'}
      </span>
    </span>
  );
}

/** Once-per-table timing-pair key, aligned to the stacked pair in every cell. */
function RowKey({ labels }: { labels: [string, string] }) {
  return (
    <span className="flex h-[44px] flex-col items-end justify-center gap-2.5">
      <span className="text-muted-foreground/70 flex h-[17px] items-center text-[11.5px] font-semibold tracking-wider uppercase whitespace-nowrap">
        {labels[0]}
      </span>
      <span className="text-muted-foreground/70 flex h-[17px] items-center text-[11.5px] font-semibold tracking-wider uppercase">
        {labels[1]}
      </span>
    </span>
  );
}

