interface PerfScenario {
  deploy?: number;
  'warm-deploy'?: number;
  backup?: number;
  restore?: number;
  scale?: number;
  /** Not emitted by CI yet; the failover tab reads it the day it appears. */
  failover?: number;
  destroy?: number;
}

const SCENARIOS: Record<string, Record<string, PerfScenario> | undefined> = Object.fromEntries(
  Object.entries(
    perfData.providers as Record<string, { scenarios: Record<string, PerfScenario> }>
  ).map(([id, entry]) => [id, entry.scenarios])
);

function formatDuration(ms: number): string {
  if (ms < 1_000) return `${Math.round(ms)}ms`;
  const totalSeconds = ms / 1_000;
  if (totalSeconds < 60) return `${totalSeconds.toFixed(1)}s`;
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = Math.round(totalSeconds % 60);
  const carry = Math.floor(seconds / 60);
  return `${minutes + carry}m ${seconds % 60}s`;
}

// ---------------------------------------------------------------------------
// Cells
