#!/usr/bin/env node
/**
 * Generate .env and .env.local for developing directly in the carbon/ template,
 * so everything works out of the box without running `vibecarbon create`.
 * The app creates the super admin (ADMIN_EMAIL / ADMIN_PASSWORD) on startup
 * (src/server/auth/bootstrap-admin.ts); nothing is seeded into the database.
 *
 * Usage:
 *   node scripts/dev-init.js           # Generate if missing
 *   node scripts/dev-init.js --force   # Overwrite existing files
 */

import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { formatDotenvLine, readEnvFiles } from './lib/dotenv.js';

const force = process.argv.includes('--force');

// Fixed local dev values (BETTER_AUTH_SECRET excepted, see below).
const DEV = {
  PROJECT_NAME: 'vibecarbon',
  // Random per checkout (64 characters, like `vibecarbon create`): it signs
  // session cookies, so a value shared by every checkout would let any of them
  // forge sessions for another. An existing one (from either env file) is
  // kept, so --force and a half-present pair don't sign everyone out.
  BETTER_AUTH_SECRET: existingAuthSecret() ?? randomBytes(48).toString('base64url'),
  DB_PASSWORD: 'local-postgres-password-for-dev-only',
  ADMIN_EMAIL: 'admin@example.com',
  ADMIN_PASSWORD: 'local-admin-password',
  // Must match volumes/s3/s3.json (dev-only placeholders, never used in deploys).
  S3_ACCESS_KEY: 'local-dev-s3-access-key',
  S3_SECRET_KEY: 'local-dev-s3-secret-key-not-for-production',
};

function existingAuthSecret() {
  const secret = readEnvFiles('.').BETTER_AUTH_SECRET;
  return secret && secret.length >= 32 ? secret : undefined;
}

// Every KEY=value line is built with formatDotenvLine so the generated file
// uses the same grammar Node/Docker Compose/Vite all agree on; comments and
// blank lines are literal template text.
const envLines = [
  '# =============================================================================',
  '# DEV ENVIRONMENT - Generated by `npm run dev:init`',
  '# DO NOT COMMIT THIS FILE',
  '# =============================================================================',
  '',
  '# Project',
  formatDotenvLine('PROJECT_NAME', DEV.PROJECT_NAME),
  formatDotenvLine('VITE_PROJECT_NAME', DEV.PROJECT_NAME),
  '',
  '# Auth session signing key (in-process auth, random per checkout)',
  formatDotenvLine('BETTER_AUTH_SECRET', DEV.BETTER_AUTH_SECRET),
  '',
  '# Database. The API server connects with the DB_* vars (base port:',
  '# DEV_DB_PORT or DEV_PORT_OFFSET is applied at runtime by env.ts)',
  formatDotenvLine('DB_HOST', 'localhost'),
  formatDotenvLine('DB_PORT', '5432'),
  formatDotenvLine('DB_USER', 'postgres'),
  formatDotenvLine('DB_PASSWORD', DEV.DB_PASSWORD),
  formatDotenvLine('DB_NAME', 'postgres'),
  formatDotenvLine('POSTGRES_PASSWORD', DEV.DB_PASSWORD),
  '',
  '# Super admin, created by the app at startup (password: at least 8 characters)',
  formatDotenvLine('ADMIN_EMAIL', DEV.ADMIN_EMAIL),
  formatDotenvLine('ADMIN_PASSWORD', DEV.ADMIN_PASSWORD),
  '',
  '# Site URL (base port — offset applied dynamically, see above)',
  formatDotenvLine('SITE_URL', 'http://localhost:5173'),
  '',
  "# Public URL — substituted into index.html's og:/twitter: meta tags by Vite's",
  '# %VITE_PUBLIC_URL% replacement. Must be defined or Vite warns on every reload.',
  formatDotenvLine('VITE_PUBLIC_URL', 'http://localhost:5173'),
  '',
  '# OAuth (disabled for dev)',
  formatDotenvLine('GOOGLE_ENABLED', 'false'),
  formatDotenvLine('GOOGLE_CLIENT_ID', ''),
  formatDotenvLine('GOOGLE_CLIENT_SECRET', ''),
  '',
  formatDotenvLine('MICROSOFT_ENABLED', 'false'),
  formatDotenvLine('MICROSOFT_CLIENT_ID', ''),
  formatDotenvLine('MICROSOFT_CLIENT_SECRET', ''),
  formatDotenvLine('MICROSOFT_TENANT_ID', ''),
  '',
  '# External services (disabled for dev)',
  formatDotenvLine('STRIPE_SECRET_KEY', ''),
  formatDotenvLine('STRIPE_WEBHOOK_SECRET', ''),
  formatDotenvLine('SMTP_HOST', ''),
  formatDotenvLine('SMTP_PORT', '587'),
  formatDotenvLine('SMTP_USER', ''),
  formatDotenvLine('SMTP_PASS', ''),
  '# SMTP_ADMIN_EMAIL=""',
  formatDotenvLine('SMTP_SENDER_NAME', DEV.PROJECT_NAME),
  '',
  '# Local S3 for uploads (SeaweedFS from docker-compose.override.yml, dev-only keys',
  '# matching volumes/s3/s3.json). If you change DEV_S3_PORT, change S3_ENDPOINT to match.',
  formatDotenvLine('S3_ENDPOINT', 'http://localhost:8333'),
  formatDotenvLine('S3_REGION', 'us-east-1'),
  formatDotenvLine('S3_BUCKET', `${DEV.PROJECT_NAME}-local`),
  formatDotenvLine('S3_ACCESS_KEY', DEV.S3_ACCESS_KEY),
  formatDotenvLine('S3_SECRET_KEY', DEV.S3_SECRET_KEY),
  '',
  '# Optional services',
  formatDotenvLine('VITE_N8N_ENABLED', 'false'),
  formatDotenvLine('VITE_OBSERVABILITY_ENABLED', 'false'),
  '',
  '# Analytics (Plausible - leave empty to disable)',
  formatDotenvLine('VITE_PLAUSIBLE_DOMAIN', ''),
  formatDotenvLine('VITE_PLAUSIBLE_SCRIPT_URL', ''),
  formatDotenvLine('VITE_GITHUB_REPO_URL', ''),
  '',
  '# Ports',
  formatDotenvLine('DEV_PORT_OFFSET', '0'),
  '',
  '# Environment',
  formatDotenvLine('NODE_ENV', 'development'),
  formatDotenvLine('PORT', '3000'),
  formatDotenvLine('VITE_ENVIRONMENT', 'development'),
  formatDotenvLine('VITE_APP_VERSION', '0.1.0'),
];

const envContent = `${envLines.join('\n')}\n`;

function writeEnv(filename) {
  if (existsSync(filename) && !force) {
    console.log(`  SKIP: ${filename} (exists, use --force to overwrite)`);
    return false;
  }
  writeFileSync(filename, envContent, { mode: 0o600 });
  console.log(`  ${force && existsSync(filename) ? 'OVERWRITTEN' : 'CREATED'}: ${filename}`);
  return true;
}

console.log('');
console.log('  Generating dev environment files...');
console.log('');

const wrote1 = writeEnv('.env');
const wrote2 = writeEnv('.env.local');

console.log('');
if (wrote1 || wrote2) {
  console.log(`  Admin login: ${DEV.ADMIN_EMAIL} / ${DEV.ADMIN_PASSWORD}`);
  console.log('  Run `npm run dev:start` to start all services.');
} else {
  console.log('  No files written. Use --force to overwrite existing files.');
}
console.log('');
